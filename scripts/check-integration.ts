import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import type { City, Transit } from "../src/shared/city";
import { localCohortResponses } from "../src/shared/advisors";
import { interpretLocally } from "../src/shared/localInterpreter";
import { DEFAULT_AI_CONFIG } from "../src/shared/aiConfig";
import { FRAME_CAPACITY_FACTOR, FRAME_STRIDE } from "../src/sim/protocol";
import { Engine } from "../src/sim/engine";
import { Intelligence } from "../src/sim/intelligence";
import { buildAiContext } from "../src/sim/aiContext";

const city: City = JSON.parse(readFileSync("public/city.json", "utf8"));
const transit: Transit = JSON.parse(readFileSync("public/transit.json", "utf8"));
const engine = new Engine(city, { residents: 50, tourists: 0, commuters: 0, seed: 2026, startDate: new Date("2026-10-29"), transit });
assert.equal(engine.agents.length, 50);
assert.ok(engine.bus);
assert.ok(engine.parkings);
engine.advanceTo(360);
const proposal = interpretLocally("Un concert au Pâquier", [], false);
assert.ok(proposal);
proposal.startTime = "06:10";
const sid = engine.addEvent(proposal);
assert.equal(typeof sid, "number");
const request = engine.outbox.find((message) => message.type === "cohortRequest" && message.sid === sid);
assert.ok(request && request.type === "cohortRequest");
engine.setCohortPlan(sid, localCohortResponses(request.event, request.cohorts));
engine.advanceTo(371);
const event = engine.dayPlan.events.find((event) => event.sid === sid);
assert.ok(event);
const a = engine.agents[0];
const [x, z] = [a.x, a.z];
a.x = event.x; a.z = event.z;
const context = JSON.parse(buildAiContext(engine, a, { memories: [], goal: "Organiser ma journée", plan: [] }, [], []));
assert.ok(context.nearbyEvents.some((entry: { title: string }) => entry.title === event.title.slice(0, 100)));
assert.equal(context.person.district, a.district);
a.x = x; a.z = z;
let people = 0;
globalThis.fetch = async (_url, options) => {
  const { contexts } = JSON.parse(String(options?.body));
  people += contexts.length;
  return Response.json({ decisions: contexts.map(({ agentId }: { agentId: number }) => ({ agentId, action: "continue", thought: "Je tiens compte de la vie du quartier." })) });
};
const intelligence = new Intelligence(engine);
intelligence.configure(DEFAULT_AI_CONFIG);
intelligence.tick();
await new Promise((resolve) => setTimeout(resolve, 10));
assert.equal(people, 5);
assert.ok(intelligence.inspect(0).memories.length);
const buffer = new Float32Array((engine.everyone.length + 100) * FRAME_CAPACITY_FACTOR * FRAME_STRIDE);
const count = engine.snapshot(buffer);
assert.ok(count * FRAME_STRIDE <= buffer.length);
const report = engine.endDay();
assert.equal(report.population, 50);
assert.ok(report.parking);
console.log("Main + IA : 50 résidents, bus, stationnement, décision municipale, contexte local, lot de cinq et bilan : OK");
