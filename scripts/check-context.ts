import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { Engine } from "../src/sim/engine";
import { buildAiContext } from "../src/sim/aiContext";
const engine = new Engine(JSON.parse(readFileSync("public/city.json", "utf8")), { residents: 100, tourists: 0, commuters: 0, seed: 2026, startDate: new Date("2026-10-29") });
const memories = Array.from({ length: 48 }, (_, n) => `Souvenir ${n} : ${"contexte ".repeat(80)}`);
memories[45] = "Marie te dit : Rendez-vous au lac";
const a = engine.agents[0];
const compact = buildAiContext(engine, a, { memories, goal: "Rencontrer Marie", plan: ["Répondre"] }, [], []);
const result = JSON.parse(compact);
assert.ok(result.memories.length <= 10);
assert.ok(result.memories.some((m: string) => m.includes("Rendez-vous au lac")));
assert.equal(result.person.id, a.id);
assert.equal(result.person.profile, a.profile);
assert.equal(result.person.monthlyIncome, Math.round(a.household.income / 12));
assert.equal(result.person.schedule, undefined);
const full = JSON.stringify({ person: engine.inspect(a.id), memories });
assert.ok(compact.length < full.length / 2);
console.log(`Contexte avec mémoire remplie : ${full.length} → ${compact.length} caractères (-${Math.round((1 - compact.length / full.length) * 100)} %). Identité, revenus et paroles préservés.`);
